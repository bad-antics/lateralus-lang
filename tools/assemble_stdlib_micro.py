#!/usr/bin/env python3
"""Assemble a self-contained .ltl file for the stdlib micro-benchmarks.

`import stdlib.<mod>` does not currently inject the module's symbols into the
caller's namespace (the same limitation examples/spiral_ranking.ltl documents),
so each benchmark is assembled by concatenating the module source plus a driver
that only calls the module's public functions.

    python3 tools/assemble_stdlib_micro.py xxhash > build/stdlib_micro_xxhash.ltl
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRIVERS = ROOT / "benchmarks" / "drivers"

MODULES = {
    "xxhash": [ROOT / "stdlib" / "xxhash.ltl"],
    "lz4": [ROOT / "stdlib" / "lz4.ltl"],
    "aho_corasick": [ROOT / "stdlib" / "aho_corasick.ltl"],
    "radix_sort_u32": [ROOT / "stdlib" / "radix_sort.ltl"],
    # std/crypto/chacha20.ltl is Rust pseudo-code that does not parse as
    # Lateralus; stdlib/chacha20.ltl is the real implementation.
    "chacha20": [ROOT / "stdlib" / "chacha20.ltl"],
}


def strip_module(src: str) -> str:
    """Drop import lines and any trailing main() a module may carry."""
    out = []
    for line in src.splitlines():
        stripped = line.strip()
        if stripped.startswith("import "):
            continue
        out.append(line)
    text = "\n".join(out)
    idx = text.find("\nfn main(")
    if idx != -1:
        text = text[:idx]
    return text.rstrip() + "\n"


def assemble(name: str) -> str:
    if name not in MODULES:
        raise SystemExit(f"unknown benchmark {name!r}")
    parts = [f"// Generated by tools/assemble_stdlib_micro.py — do not edit.\n// benchmark: {name}\n"]
    for path in MODULES[name]:
        parts.append(f"\n// ── from {path.relative_to(ROOT)} ──\n")
        parts.append(strip_module(path.read_text()))
    driver = DRIVERS / f"{name}_driver.ltl"
    if driver.exists():
        parts.append(f"\n// ── driver: {driver.relative_to(ROOT)} ──\n")
        parts.append(driver.read_text())
    return "".join(parts)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    sys.stdout.write(assemble(sys.argv[1]))
