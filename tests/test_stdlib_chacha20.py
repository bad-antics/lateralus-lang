"""
Regression and verification tests for stdlib/chacha20.ltl.
Validates RFC 8439 ChaCha20 stream cipher implementation and official test vectors.
"""
from pathlib import Path
from lateralus_lang.compiler import Compiler, Target

REPO_ROOT = Path(__file__).resolve().parent.parent
CHACHA20_LTL = REPO_ROOT / "stdlib" / "chacha20.ltl"


def test_chacha20_compiler_targets():
    """Ensure stdlib/chacha20.ltl compiles cleanly across all primary backends."""
    source = CHACHA20_LTL.read_text("utf-8")
    for target in [Target.PYTHON, Target.JAVASCRIPT, Target.C]:
        result = Compiler().compile_source(source, target=target)
        assert result.ok, f"Target {target.name} compile failed: {result.errors}"


def test_chacha20_rfc8439_block_vector():
    """Verify RFC 8439 Section 2.3.2 keystream block vector."""
    # Key: 0x00, 0x01, ..., 0x1f (32 bytes)
    key = list(range(32))
    # Nonce: 00:00:00:09:00:00:00:4a:00:00:00:00 (12 bytes)
    nonce = [0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x4a, 0x00, 0x00, 0x00, 0x00]
    counter = 1

    # RFC 8439 Section 2.3.2 serialized keystream block
    expected_keystream = [
        0x10, 0xf1, 0xe7, 0xe4, 0xd1, 0x3b, 0x59, 0x15,
        0x50, 0x0f, 0xdd, 0x1f, 0xa3, 0x20, 0x71, 0xc4,
        0xc7, 0xd1, 0xf4, 0xc7, 0x33, 0xc0, 0x68, 0x03,
        0x04, 0x22, 0xaa, 0x9a, 0xc3, 0xd4, 0x6c, 0x4e,
        0xd2, 0x82, 0x64, 0x46, 0x07, 0x9f, 0xaa, 0x09,
        0x14, 0xc2, 0xd7, 0x05, 0xd9, 0x8b, 0x02, 0xa2,
        0xb5, 0x12, 0x9c, 0xd1, 0xde, 0x16, 0x4e, 0xb9,
        0xcb, 0xd0, 0x83, 0xe8, 0xa2, 0x50, 0x3c, 0x4e,
    ]

    source = CHACHA20_LTL.read_text("utf-8")
    comp = Compiler().compile_source(source, target=Target.PYTHON)
    assert comp.ok, f"Compile failed: {comp.errors}"

    ns = {}
    exec(comp.python_src, ns)
    block_fn = ns.get("block")
    assert callable(block_fn), "block function missing in compiled output"

    out = block_fn(key, nonce, counter)
    assert out == expected_keystream, f"Keystream mismatch:\nGot:      {out}\nExpected: {expected_keystream}"


def test_chacha20_rfc8439_encryption_vector():
    """Verify RFC 8439 Section 2.4.2 encryption test vector."""
    # Key: 0x00, 0x01, ..., 0x1f
    key = list(range(32))
    # Nonce: 00:00:00:00:00:00:00:4a:00:00:00:00
    nonce = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x4a, 0x00, 0x00, 0x00, 0x00]
    counter = 1

    plaintext = "Ladies and Gentlemen of the class of '99: If I could offer you only one tip for the future, sunscreen would be it."
    pt_bytes = [ord(c) for c in plaintext]

    # RFC 8439 Section 2.4.2 official ciphertext
    expected_ciphertext = [
        0x6e, 0x2e, 0x35, 0x9a, 0x25, 0x68, 0xf9, 0x80,
        0x41, 0xba, 0x07, 0x28, 0xdd, 0x0d, 0x69, 0x81,
        0xe9, 0x7e, 0x7a, 0xec, 0x1d, 0x43, 0x60, 0xc2,
        0x0a, 0x27, 0xaf, 0xcc, 0xfd, 0x9f, 0xae, 0x0b,
        0xf9, 0x1b, 0x65, 0xc5, 0x52, 0x47, 0x33, 0xab,
        0x8f, 0x59, 0x3d, 0xab, 0xcd, 0x62, 0xb3, 0x57,
        0x16, 0x39, 0xd6, 0x24, 0xe6, 0x51, 0x52, 0xab,
        0x8f, 0x53, 0x0c, 0x35, 0x9f, 0x08, 0x61, 0xd8,
        0x07, 0xca, 0x0d, 0xbf, 0x50, 0x0d, 0x6a, 0x61,
        0x56, 0xa3, 0x8e, 0x08, 0x8a, 0x22, 0xb6, 0x5e,
        0x52, 0xbc, 0x51, 0x4d, 0x16, 0xcc, 0xf8, 0x06,
        0x81, 0x8c, 0xe9, 0x1a, 0xb7, 0x79, 0x37, 0x36,
        0x5a, 0xf9, 0x0b, 0xbf, 0x74, 0xa3, 0x5b, 0xe6,
        0xb4, 0x0b, 0x8e, 0xed, 0xf2, 0x78, 0x5e, 0x42,
        0x87, 0x4d
    ]

    source = CHACHA20_LTL.read_text("utf-8")
    comp = Compiler().compile_source(source, target=Target.PYTHON)
    assert comp.ok, f"Compile failed: {comp.errors}"

    ns = {}
    exec(comp.python_src, ns)
    xor_fn = ns.get("xor")
    assert callable(xor_fn), "xor function missing in compiled output"

    # Encryption
    ct = xor_fn(key, nonce, counter, pt_bytes)
    assert ct == expected_ciphertext, f"Ciphertext mismatch:\nGot:      {ct}\nExpected: {expected_ciphertext}"

    # Decryption (XOR roundtrip)
    decrypted = xor_fn(key, nonce, counter, ct)
    assert decrypted == pt_bytes, "Decryption roundtrip failed"
